#!/usr/bin/env node
/**
 * Contact sheets for every timestamped moment in references/references.md, so Claude can study how
 * things move between frames and describe each moment back before it becomes a beat.
 *
 *   npm run refs            only moments that don't have a sheet yet
 *   npm run refs -- --all   redo every sheet
 *
 * Reads entries shaped like:
 *   ## 4. `clip-name.mp4` — Creator name
 *   - **00:11–00:14** — what happens...
 * Writes work/refs/<clip>-<mm.ss>-<mm.ss>.jpg and work/refs/INDEX.md (moment -> sheet), and lists
 * clips that are in the folder but have no entry yet, or entries whose clip is missing.
 */
import {spawnSync} from 'node:child_process';
import {existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {basename, extname, join} from 'node:path';

// Never hardcode a tool path. media.mjs finds the ffmpeg that ships with the studio
// (ffmpeg-static, pulled in by npm install) before it looks at PATH, which is what lets this
// run on a machine that has never had ffmpeg installed on it. A hardcoded path failed
// silently here: the sheets were simply never generated and nothing said why.
import {FFMPEG} from './lib/media.mjs';

const REF_DIR = 'references';
const OUT = join('work', 'refs');
const all = process.argv.includes('--all');
mkdirSync(OUT, {recursive: true});

const md = readFileSync(join(REF_DIR, 'references.md'), 'utf8');
const secs = (t) => t.split(':').reduce((s, v) => s * 60 + Number(v), 0);

const entries = [];
let clip = null;
for (const line of md.split('\n')) {
  const head = line.match(/^##\s+\d+\.\s+`([^`]+)`/);
  if (head) {
    clip = head[1];
    continue;
  }
  if (line.startsWith('## ')) clip = null;
  const moment = clip && line.match(/^-\s+\*\*(\d{1,2}:\d{2})(?:\s*[–-]\s*(\d{1,2}:\d{2}))?\*\*\s*[—–-]\s*(.*)$/);
  if (moment) entries.push({clip, from: moment[1], to: moment[2], note: moment[3]});
}

const index = ['# Reference contact sheets', '', 'Frames left to right, top to bottom. Generated by `npm run refs`.', ''];
const missing = new Set();
let made = 0;
for (const e of entries) {
  const src = join(REF_DIR, e.clip);
  if (!existsSync(src)) {
    missing.add(e.clip);
    continue;
  }
  const tag = `${basename(e.clip, extname(e.clip)).toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${e.from.replace(':', '.')}${e.to ? `-${e.to.replace(':', '.')}` : ''}`;
  const sheet = join(OUT, `${tag}.jpg`);
  if (all || !existsSync(sheet)) {
    const start = Math.max(0, secs(e.from) - 0.3);
    const len = Math.max(1, (e.to ? secs(e.to) : secs(e.from) + 1) - start + 0.3);
    // ~18 frames spread over the moment (3-8 fps), 6 per row.
    const fps = Math.min(8, Math.max(3, Math.round(18 / len)));
    const r = spawnSync(FFMPEG, ['-y', '-loglevel', 'error', '-ss', String(start), '-t', String(len), '-i', src, '-vf', `fps=${fps},scale=320:-2,tile=6x3`, '-frames:v', '1', sheet]);
    if (r.status === 0) made++;
  }
  index.push(`- \`${e.clip}\` ${e.from}${e.to ? `–${e.to}` : ''} — ${e.note.slice(0, 90)}${e.note.length > 90 ? '…' : ''} → \`${sheet.split('\\').join('/')}\``);
}

const described = new Set(entries.map((e) => e.clip));
const unlisted = readdirSync(REF_DIR).filter((f) => /\.(mp4|mov|webm|m4v)$/i.test(f) && !described.has(f));
index.push('');
if (unlisted.length) index.push(`Clips with no entry in references.md yet: ${unlisted.join(', ')}`);
if (missing.size) index.push(`Entries whose clip is missing from references/: ${[...missing].join(', ')}`);
writeFileSync(join(OUT, 'INDEX.md'), `${index.join('\n')}\n`);

console.log(`${entries.length} moments in references.md · ${made} new sheet(s) · index: ${join(OUT, 'INDEX.md')}`);
if (unlisted.length) console.log(`No entry yet: ${unlisted.join(', ')}`);
if (missing.size) console.log(`Clip missing: ${[...missing].join(', ')}`);
